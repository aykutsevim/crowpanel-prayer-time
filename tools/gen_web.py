"""Build the setup page and the place list into the firmware (spec 004 FR-013, SC-006, research R7).

Inputs:  data/portal/index.html, style.css, logic.js, ui.js, app.js; data/places_tr.json.
Output:  src/generated/web_assets.h and web_assets.cpp (git-ignored), holding
         * portal_html_gz: the page as one self-contained document, gzip-compressed;
         * places_json_gz: the place list, gzip-compressed, served as /places.json;
         * places_json:    the same list uncompressed, for nvp::net::place_lookup on the device.

Minifying is conservative (comments and leading whitespace only; lines are kept, so JavaScript's
automatic semicolons still hold). gzip runs with mtime 0, so the output is the same on every run.
The build fails when the page is over 25 600 bytes gzipped (02 §10).

Run by tools/pio_gen_web.py before every firmware build, or by hand: python tools/gen_web.py
"""
from __future__ import annotations

import gzip
import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PORTAL = ROOT / "data" / "portal"
PLACES = ROOT / "data" / "places_tr.json"
OUT_DIR = ROOT / "src" / "generated"
PAGE_BUDGET = 25600
SCRIPTS = ("logic.js", "ui.js", "app.js")


class WebError(Exception):
    pass


def strip_block_comments(text: str) -> str:
    return re.sub(r"/\*.*?\*/", "", text, flags=re.S)


def squeeze(text: str) -> str:
    """Leading and trailing whitespace off every line, empty lines dropped."""
    return "\n".join(line.strip() for line in text.splitlines() if line.strip())


def strip_line_comments(js: str) -> str:
    """Drops whole-line // comments only (a // inside a line may be part of a string or URL)."""
    return "\n".join(line for line in js.splitlines() if not line.strip().startswith("//"))


def build_page(portal: Path = PORTAL) -> bytes:
    html = (portal / "index.html").read_text(encoding="utf-8")
    css = squeeze(strip_block_comments((portal / "style.css").read_text(encoding="utf-8")))
    js = "\n".join(squeeze(strip_line_comments(strip_block_comments((portal / n).read_text(encoding="utf-8"))))
                   for n in SCRIPTS)
    if "/*STYLE*/" not in html or "/*SCRIPT*/" not in html:
        raise WebError("index.html lacks the /*STYLE*/ or /*SCRIPT*/ placeholder")
    if "</script" in js.lower():
        raise WebError("a script contains </script")
    page = squeeze(html).replace("/*STYLE*/", css).replace("/*SCRIPT*/", js)
    for bad in ("http://", "https://", "//cdn", "@import", "url("):
        if bad in page.replace("http://192.168.4.1", ""):
            raise WebError(f"the page must make no external requests (found {bad!r})")
    return page.encode("utf-8")


def build_places(path: Path = PLACES) -> bytes:
    if not path.is_file():
        raise WebError(f"{path.relative_to(ROOT)} is missing: run python tools/gen_places.py")
    doc = json.loads(path.read_text(encoding="utf-8"))
    if "provinces" not in doc:
        raise WebError(f"{path.name} has no provinces")
    return json.dumps(doc, ensure_ascii=False, separators=(",", ":")).encode("utf-8")


def gz(data: bytes) -> bytes:
    return gzip.compress(data, compresslevel=9, mtime=0)


def c_array(name: str, data: bytes, char: bool = False) -> str:
    kind = "char" if char else "unsigned char"
    body = ",\n".join("    " + ",".join(f"0x{b:02x}" for b in data[i:i + 20]) for i in range(0, len(data), 20))
    extra = ",0x00" if char else ""  # a C string for place_lookup's callers
    return (f"// sha256 {hashlib.sha256(data).hexdigest()}\n"
            f"extern const {kind} {name}[] = {{\n{body}{extra}\n}};\n"
            f"extern const size_t {name}_len = {len(data)};\n")


HEADER = """// Generated by tools/gen_web.py from data/ (spec 004 R7). Do not edit; not in git.
#pragma once

#include <cstddef>

namespace generated {
extern const unsigned char portal_html_gz[];
extern const size_t portal_html_gz_len;
extern const unsigned char places_json_gz[];
extern const size_t places_json_gz_len;
extern const char places_json[];  // NUL-terminated
extern const size_t places_json_len;
}  // namespace generated
"""


def render(page: bytes, places: bytes) -> tuple[str, str]:
    source = ("// Generated by tools/gen_web.py from data/ (spec 004 R7). Do not edit; not in git.\n"
              '#include "generated/web_assets.h"\n\nnamespace generated {\n\n'
              + c_array("portal_html_gz", gz(page)) + "\n"
              + c_array("places_json_gz", gz(places)) + "\n"
              + c_array("places_json", places, char=True)
              + "\n}  // namespace generated\n")
    return HEADER, source


def write_if_changed(path: Path, text: str) -> bool:
    if path.is_file() and path.read_text(encoding="utf-8") == text:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")
    return True


def main() -> int:
    page = build_page()
    places = build_places()
    page_gz = len(gz(page))
    if page_gz > PAGE_BUDGET:
        raise WebError(f"setup page is {page_gz} B gzipped, over the {PAGE_BUDGET} B budget (02 §10)")
    header, source = render(page, places)
    changed = write_if_changed(OUT_DIR / "web_assets.h", header) | write_if_changed(OUT_DIR / "web_assets.cpp", source)
    print(f"gen_web: page {len(page)} B, {page_gz} B gzipped (budget {PAGE_BUDGET} B); "
          f"places {len(places)} B, {len(gz(places))} B gzipped{'' if changed else ' (unchanged)'}")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except WebError as e:
        sys.exit(f"gen_web: {e}")
